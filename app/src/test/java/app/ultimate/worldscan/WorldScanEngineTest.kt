        assertTrue("yaw ${reg.alignment.yawDeg}", angleDiff(reg.alignment.yawDeg.toDouble(), truth.yawDeg.toDouble()) < 0.8)
        assertTrue(hypot((reg.alignment.dx - truth.dx).toDouble(), (reg.alignment.dz - truth.dz).toDouble()) < 0.25)

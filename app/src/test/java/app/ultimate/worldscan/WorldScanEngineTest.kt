    private fun angleDiff(a: Double, b: Double) = abs(((a - b + 540.0) % 360.0) - 180.0)

    // ---------------------------------------------------------------- clock
    @Test fun clockSyncFollowsAnOffsetAndDriftAndReportsItsOwnJitter() {
        val rnd = Random(1); val sync = ClockSync()
        val offset0 = 123_456_000_000L; val driftPpm = 20.0; val minLatency = 25_000_000L
        var worstErr = 0L
        var t = 1_000_000_000L
        val truth = { frame: Long -> offset0 + (driftPpm * 1e-6 * frame).toLong() + minLatency }
        for (i in 0 until 6000) {            // 200 s at 30 frames per second
            val latency = minLatency + (-kotlin.math.ln(1 - rnd.nextDouble()) * 12e6).toLong()      // never below 25 ms, 12 ms typical extra
            sync.add(t, t + offset0 + (driftPpm * 1e-6 * t).toLong() + latency)
            t += 33_333_333L
            if (i > 600 && i % 50 == 0) worstErr = maxOf(worstErr, abs((sync.offsetAt(t) ?: 0L) - truth(t)))
        }
        assertTrue("offset error ${worstErr / 1e6} ms", worstErr < 6_000_000L)
        assertTrue("jitter ${sync.jitterNs / 1e6} ms", sync.jitterNs in 8_000_000L..18_000_000L)
        assertEquals(false, sync.sameClock)
        val d = sync.driftMsPerHour!!
        assertTrue("drift $d ms/h", d in 40.0..105.0)     // 20 ppm = 72 ms/h
    }

    @Test fun clockSyncRecognisesTheSensorClockItself() {
        val sync = ClockSync(); var t = 5_000_000_000L
        repeat(500) { sync.add(t, t + 40_000_000L); t += 33_333_333L }
        assertEquals(true, sync.sameClock)
        assertTrue(sync.ready)
        assertEquals(5_000_000_000L + 40_000_000L, sync.toElapsed(5_000_000_000L)!!)
    }


    // ---------------------------------------------------------------- track
    private fun pose(t: Double, x: Float, z: Float, q: TrackingQuality = TrackingQuality.TRACKING) = PosePoint((t * 1e9).toLong(), x, 0f, z, 0f, 0f, 0f, 1f, q)

    @Test fun trackInterpolatesAndRefusesToGuessAcrossGaps() {
        val t = WalkTrack()
        t.add(pose(0.0, 0f, 0f)); t.add(pose(1.0, 2f, 0f)); t.add(pose(5.0, 6f, 0f)); t.add(pose(6.0, 6f, 1f, TrackingQuality.NOT_TRACKING)); t.add(pose(7.0, 6f, 2f))
        assertEquals(1f, t.at(500_000_000L)!!.x, 1e-4f)
        assertNull("4 s gap", t.at(3_000_000_000L))
        assertNull("not tracked neighbour", t.at(6_500_000_000L))
        assertNull(t.at(-1L)); assertNull(t.at(9_000_000_000L))
        assertFalse("out of order", t.add(pose(2.0, 0f, 0f)))
        assertFalse("not finite", t.add(pose(8.0, Float.NaN, 0f)))
    }

    @Test fun trackMeasuresLengthIgnoresJumpsAndRoundTripsThroughDisk() {
        val t = WalkTrack()
        for (i in 0..100) t.add(pose(i * 0.1, i * 0.14f, 0f))        // 14 m at 1.4 m/s
        t.add(pose(10.1, 500f, 0f))                                    // tracking jumped 486 m in 0.1 s
        for (i in 1..10) t.add(pose(10.1 + i * 0.1, 500f + i * 0.14f, 0f))
        assertEquals(1, t.jumps)
        assertEquals(14.0 + 1.4, t.lengthM, 0.2)
        assertEquals(1.4, t.speedP95, 0.05)
        assertEquals(1.0, t.trackedShare, 1e-9)
        val bytes = ByteArrayOutputStream(); t.write(bytes)
        val back = WalkTrack.read(ByteArrayInputStream(bytes.toByteArray()))
        assertEquals(t.points.size, back.points.size); assertEquals(t.lengthM, back.lengthM, 1e-9)
        assertEquals(0.14f * 50, back.points[50].x, 1e-4f)
    }


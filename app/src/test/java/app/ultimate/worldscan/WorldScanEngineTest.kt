    @Test fun theStoreKeepsEveryWalkMergesCarefullyAndUndoes() {
        val dir = File(System.getProperty("java.io.tmpdir"), "worldscan" + System.nanoTime()); val store = WalkStore(dir)
        // Walk 1 defines the place: its pieces are in its own session frame.
        val first = (0 until 4).map { i -> WalkChunk(WorldSim.mapOf(WorldSim.street, (i * 15f)..((i + 1) * 15f), Random(10 + i)), i * 15_000_000_000L, (i + 1) * 15_000_000_000L - 1) }
        val r1 = store.save(walkInput("w1", first), null)
        assertEquals(1, store.places().size)
        val pid = r1.place.id
        val baseCubes = store.baseMap(pid)!!.solid
        assertTrue(baseCubes > 5000)
        // Walk 2 is the same street in another session frame.
        val r2 = store.save(walkInput("w2", piecesOf(Random(2), 6f, 54f, 4)), pid)
        assertTrue(r2.merge!!.summary(), r2.merge!!.accepted)
        val place = store.place(pid)!!
        assertEquals(2, place.walks.size); assertEquals(listOf("w2"), place.mergeOrder)
        val w2 = place.walks.first { it.id == "w2" }
        assertNotNull(w2.merge); assertTrue(w2.merge!!.used >= 3)
        assertTrue("angle ${w2.merge!!.global.yawDeg}", angleDiff(w2.merge!!.global.yawDeg.toDouble(), truth.yawDeg.toDouble()) < 1.0)
        // Raw pieces of both walks are still there, whatever happened to the merged map.
        assertEquals(4, store.pieces(pid, "w1").size); assertEquals(4, store.pieces(pid, "w2").size)
        assertNotNull(store.track(pid, "w2"))
        // Undo puts the map back exactly and leaves the walk stored, now marked unmerged.
        val afterMerge = store.baseMap(pid)!!.solid
        assertTrue(store.canUndo(pid))
        assertTrue(store.undoLastMerge(pid))
        assertEquals(baseCubes, store.baseMap(pid)!!.solid)
        assertNull(store.place(pid)!!.walks.first { it.id == "w2" }.merge)
        assertTrue(afterMerge >= baseCubes * 0.97)
        // It can be merged again.
        assertTrue(store.retryMerge(pid, "w2")!!.accepted)
        // An unrelated walk is stored apart, with the reason, and the map does not change.
        val cubesNow = store.baseMap(pid)!!.solid
        val junk = listOf(WalkChunk(WorldSim.inSession(WorldSim.mapOf(listOf(app.ultimate.room.Box(0f, 0f, -9f, 5f, 7f, -8f), app.ultimate.room.Box(9f, 0f, -12f, 17f, 14f, -8f), app.ultimate.room.Box(30f, 0f, 3f, 36f, 9f, 9f)), 0f..60f, Random(9)), truth), 0L, 1L))
        val r3 = store.save(walkInput("w3", junk), pid)
        assertFalse(r3.merge!!.accepted); assertNotNull(r3.walk.unmergedReason)
        assertEquals(cubesNow, store.baseMap(pid)!!.solid)
        assertEquals(1, store.pieces(pid, "w3").size)
        assertEquals(3, store.place(pid)!!.walks.size)
        store.deletePlace(pid); assertEquals(0, store.places().size); dir.deleteRecursively()
    }


    @Test fun aDifferentPlaceIsRefusedAndTheSavedMapIsUntouched() {
        val base = WorldSim.mapOf(WorldSim.street, 0f..80f, Random(100))
        val other = listOf(app.ultimate.room.Box(0f, 0f, -9f, 5f, 7f, -8f), app.ultimate.room.Box(9f, 0f, -12f, 17f, 14f, -8f), app.ultimate.room.Box(20f, 0f, -8.5f, 23f, 4f, -8f), app.ultimate.room.Box(30f, 0f, 3f, 36f, 9f, 9f), app.ultimate.room.Box(50f, 0f, -20f, 52f, 5f, 12f))
        val fresh = WorldSim.inSession(WorldSim.mapOf(other, 0f..60f, Random(9)), truth)
        val pointsBefore = base.points().map { Triple(it.x, it.y, it.z) }.toSet()
        val out = WalkFusion.merge(base, listOf(WalkChunk(fresh, 0L, 1L)), null, null)
        assertFalse(out.summary(), out.accepted)
        assertEquals(pointsBefore, base.points().map { Triple(it.x, it.y, it.z) }.toSet())
    }

    @Test fun aDriftingWalkIsFittedPieceByPieceAndFitsBetterThanOneRigidMove() {
        val base = WorldSim.mapOf(WorldSim.street, 0f..80f, Random(100))
        // Motion tracking drifts: each ~10 m piece of the walk has accumulated a little more turn and shift than the one before.
        val pieces = piecesOf(Random(2), 0f, 80f, 8, drift = { i -> Alignment(0.05f * i, 0.07f * i, 0f, -0.05f * i) })
        val sBase = Structure.of(base)
        val out = WalkFusion.merge(base, pieces, null, null)
        assertTrue(out.summary(), out.accepted)
        assertTrue("fitted individually: ${out.refined}", out.refined >= 4)
        // The same pieces under the single whole-walk placement fit worse than under their own.
        val field = WalkAligner.field(sBase)
        val rigid = pieces.map { WalkAligner.evaluate(field, Structure.of(it.map), out.global!!.alignment.copy(dy = out.dy!!)).first }.average() * 100
        val own = out.meanCm
        assertTrue("piecewise $own cm vs rigid $rigid cm", own < rigid)
        assertTrue("piecewise fit $own cm", own < 13f)
    }


    // ---------------------------------------------------------------- finding one walk in another
    private val truth = Alignment(23.5f, 7.2f, 1.3f, -4.1f)       // fresh session -> saved frame

    private fun piecesOf(rnd: Random, x0: Float, x1: Float, n: Int, drift: (Int) -> Alignment? = { null }, seed: Int = 1): List<WalkChunk> {
        val w = (x1 - x0) / n
        return (0 until n).map { i ->
            val world = WorldSim.mapOf(WorldSim.street, (x0 + i * w)..(x0 + (i + 1) * w), Random(seed + i))
            val inSession = WorldSim.inSession(world, truth)
            val m = drift(i)?.let { d -> inSession.mapped { d.apply(it) } } ?: inSession
            WalkChunk(m, (i * 15L) * 1_000_000_000L, ((i + 1) * 15L) * 1_000_000_000L - 1)
        }
    }

    @Test fun aWalkIsFoundInASavedMapWithNoGpsAtAll() {
        val base = WorldSim.mapOf(WorldSim.street, 0f..80f, Random(100))
        val before = base.solid
        val out = WalkFusion.merge(base, piecesOf(Random(2), 8f, 62f, 4), null, null)
        assertTrue(out.summary(), out.accepted)
        val g = out.global!!.alignment
        assertTrue("yaw ${g.yawDeg}", angleDiff(g.yawDeg.toDouble(), truth.yawDeg.toDouble()) < 0.8)
        assertTrue("shift ${g.dx},${g.dz}", hypot((g.dx - truth.dx).toDouble(), (g.dz - truth.dz).toDouble()) < 0.25)
        assertEquals(truth.dy, out.dy!!, 0.12f)
        assertTrue("mean ${out.global.meanDist}", out.global.meanDist < 0.15f)
        assertTrue(out.used >= 3)
        assertTrue("map did not shrink: ${base.solid} vs $before", base.solid >= before * 0.97)
    }

    @Test fun theSearchWindowFromTwoGpsPlacementsContainsTheTruth() {
        // Two walks on the same Earth with different headings: the prior must equal composing east/north with each frame.
        val base = GeoRegistration(anchor, 0.3, 10.0, 20.0, 1.0, 2.0, 1.0, 3.0, 50, 50, 1.0, 1.0, GeoLevel.GOOD, "ok")
        val fresh = GeoRegistration(anchor, 0.9, 40.0, -15.0, 1.5, 2.5, 1.0, 3.0, 50, 50, 1.0, 1.0, GeoLevel.GOOD, "ok")
        val pr = WalkFusion.prior(fresh, base)!!
        val a = Alignment(pr.yawDeg, pr.dx, 0f, pr.dz)
        for (p in listOf(P3(0f, 0f, 0f), P3(17f, 0f, -9f), P3(-30f, 0f, 44f))) {
            val (e, n) = fresh.toEnu(p.x, p.z); val (bx, bz) = base.toLocal(e, n); val q = a.apply(p)
            assertEquals(bx, q.x, 0.05f); assertEquals(bz, q.z, 0.05f)
        }
        assertNull(WalkFusion.prior(fresh, GeoRegistration(anchor, 0.0, 0.0, 0.0, 90.0, Double.NaN, Double.NaN, Double.NaN, 0, 0, 1.0, Double.NaN, GeoLevel.NONE, "no")))
    }

    @Test fun aPriorMakesTheSearchTightAndStillFindsTheTruth() {
        val sBase = Structure.of(WorldSim.mapOf(WorldSim.street, 0f..80f, Random(100)))
        val fresh = piecesOf(Random(2), 8f, 62f, 1)[0]

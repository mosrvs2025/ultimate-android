    /** An L-shaped walk in the phone's own frame, with GPS fixes of known truth and realistic defects (a slow bias plus white noise). */
    private fun lWalk(theta: Double, tx: Double, ty: Double, seconds: Int = 140, sigma: Double = 1.5, bias: Double = 1.2, outlierAt: Int = -1, mirror: Boolean = false, rnd: Random = Random(7)): Pair<WalkTrack, List<GeoFix>> {
        val track = WalkTrack(); val fixes = ArrayList<GeoFix>()
        var bx = 0.0; var by = 0.0
        for (s in 0..seconds) {
            val d = s * 1.0
            val ax: Double; val ay: Double      // plane coordinates (x, -z)
            if (d <= 80.0) { ax = d; ay = 0.0 } else { ax = 80.0; ay = -(d - 80.0) }
            for (k in 0 until 10) {
                val dd = d + k / 10.0
                val px = if (dd <= 80.0) dd else 80.0; val py = if (dd <= 80.0) 0.0 else -(dd - 80.0)
                track.add(PosePoint(((s * 10 + k) * 100_000_000L), px.toFloat(), 0f, (-py).toFloat(), 0f, 0f, 0f, 1f, TrackingQuality.TRACKING))
            }
            bx = 0.9 * bx + Sim.gauss(rnd) * bias * 0.4; by = 0.9 * by + Sim.gauss(rnd) * bias * 0.4
            val c = cos(theta); val sn = sin(theta)
            var e = c * ax - sn * ay + tx + bx + Sim.gauss(rnd) * sigma; var n = sn * ax + c * ay + ty + by + Sim.gauss(rnd) * sigma
            if (s == outlierAt) { e += 60.0; n -= 45.0 }
            if (mirror) e = -e
            val ll = anchor.unproject(e, n)
            fixes += GeoFix(ll.first, ll.second, null, 5f, s * 1_000_000_000L)
        }
        return track to fixes
    }

    @Test fun geoFitRecoversHeadingAndStatesItsUncertainty() {
        val theta = Math.toRadians(37.0)
        val (track, fixes) = lWalk(theta, 120.0, -45.0)
        val reg = GeoFit.fit(track, fixes, anchor)
        val errDeg = Math.toDegrees(abs(reg.thetaRad - theta))
        assertEquals(GeoLevel.GOOD, reg.level)
        assertTrue("heading error $errDeg°", errDeg < 2.0)
        assertTrue("claimed ±${reg.yawSigmaDeg}° but error was $errDeg°", errDeg < 4 * reg.yawSigmaDeg + 0.5)
        val (e, n) = reg.toEnu(80f, 0f)
        val c = cos(theta); val s = sin(theta)
        assertTrue(hypot(e - (c * 80 + 120.0), n - (s * 80 - 45.0)) < 4.0)
        // Local <-> east/north round trip, and the compass bearing of the walk's -Z axis.
        val (lx, lz) = reg.toLocal(e, n); assertEquals(80f, lx, 0.01f); assertEquals(0f, lz, 0.01f)
        assertEquals((((-Math.toDegrees(reg.thetaRad)) % 360.0) + 360.0) % 360.0, reg.northOffsetDeg, 1e-6)
    }

    @Test fun anOutlierFixDoesNotDragTheFit() {
        val theta = Math.toRadians(-110.0)
        val (track, fixes) = lWalk(theta, -30.0, 80.0, outlierAt = 50)
        val reg = GeoFit.fit(track, fixes, anchor)
        assertTrue(Math.toDegrees(abs(reg.thetaRad - theta)) < 2.5)
        assertTrue(reg.used >= reg.total - 3)
    }

    @Test fun aShortStraightWalkIsNeverPlacedOnTheMap() {
        val track = WalkTrack(); val fixes = ArrayList<GeoFix>(); val rnd = Random(3)
